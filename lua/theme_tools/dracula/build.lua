-- Development-only generator. The generated colorscheme has no build dependency.
local M = {}

local function keys(t)
  local result = vim.tbl_keys(t)
  table.sort(result)
  return result
end

local function literal(value)
  if type(value) == "string" then
    return string.format("%q", value)
  end
  if type(value) ~= "table" then
    return tostring(value)
  end
  local fields = {}
  for _, key in ipairs(keys(value)) do
    fields[#fields + 1] = key .. " = " .. literal(value[key])
  end
  return "{ " .. table.concat(fields, ", ") .. " }"
end

function M.definitions()
  local c = require("theme_tools.dracula.palette")
  local groups = {}
  for _, category in ipairs({ "editor", "syntax", "integrations", "custom" }) do
    for name, value in pairs(require("theme_tools.dracula.groups." .. category)(c)) do
      groups[name] = value
    end
  end
  return groups, require("theme_tools.dracula.terminal")(c)
end

function M.render()
  local groups, terminal = M.definitions()
  local lines = {
    "-- Generated by scripts/build_dracula.lua; edit lua/theme_tools/dracula instead.",
    "-- Derived from Mofiqul/dracula.nvim (MIT); see LICENSE.dracula.",
    "-- stylua: ignore start",
    'vim.cmd("highlight clear")',
    "vim.g.colors_name = nil",
    'vim.o.background = "dark"',
    "vim.o.termguicolors = true",
    'vim.g.colors_name = "theme-tools-dracula"',
    "local h = vim.api.nvim_set_hl",
  }
  for _, name in ipairs(keys(terminal)) do
    lines[#lines + 1] = "vim.g." .. name .. " = " .. literal(terminal[name])
  end
  for _, name in ipairs(keys(groups)) do
    lines[#lines + 1] = string.format("h(0, %q, %s)", name, literal(groups[name]))
  end
  lines[#lines + 1] = "-- stylua: ignore end"
  return table.concat(lines, "\n") .. "\n"
end

return M
